/**
 * Seed the Supabase `products` table with the master product list.
 * Safe to run multiple times — uses upsert on `name`.
 * Call once from a one-off script or temporary /api/seed route.
 *
 * @param {import('@supabase/supabase-js').SupabaseClient} supabaseAdmin
 */
export async function seedMasterProducts(supabaseAdmin) {
  const { error } = await supabaseAdmin
    .from('products')
    .upsert(MASTER_PRODUCTS, { onConflict: 'name' });

  if (error) throw error;
  console.log(`Seeded ${MASTER_PRODUCTS.length} products into Supabase`);
}
